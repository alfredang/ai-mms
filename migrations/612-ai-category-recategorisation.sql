-- 612-ai-category-recategorisation.sql
-- Re-categorise AI courses into the correct "AI Series" categories.
--
-- Problem: AI courses were sprayed across the wrong series -- generic certs
-- (CompTIA Server+/A+/CISSP) and Power Apps / Power Automate sat in
-- "Generative AI Series", and agent / multi-agent courses were duplicated into
-- Generative AI + AI Applications instead of the AI Agents / Agentic AI series.
--
-- Rules applied:
--   * Each AI course is assigned to 1-2 series chosen for genuine topical relevance.
--   * Every AI course also gets the parent umbrella 252 (AI Courses).
--   * Non-AI courses are removed from the AI tree ONLY -- their non-AI
--     categories are untouched, and NO course is ever disabled or deleted.
--   * WSQ (TGS-) membership of 414 (Vibe Coding) is curated manually and is
--     never added here.
--
-- Keyed by SKU (never entity_id) so it is correct on any instance -- see
-- feedback_sku_migrations_hit_partners_irreversibly. Guarded so partner
-- M-prefix SKUs can never match.
--
-- Idempotent: re-running converges to the same membership.
-- Writes BOTH catalog_category_product and catalog_category_product_index
-- (the storefront reads the index; there is no reindex hook at deploy).
-- NEVER name a flat table here -- see category-ordering skill (590 outage).

DROP TEMPORARY TABLE IF EXISTS tmp_ai_want;
CREATE TEMPORARY TABLE tmp_ai_want (sku VARCHAR(64), category_id INT, PRIMARY KEY (sku, category_id));

