-- 1) REMOVE every AI-tree assignment that is not in the desired set.
--    Covers both non-AI courses and AI courses in the wrong series.
DELETE cp FROM catalog_category_product cp
JOIN catalog_product_entity e ON e.entity_id = cp.product_id
LEFT JOIN tmp_ai_want w ON w.sku = e.sku AND w.category_id = cp.category_id
WHERE cp.category_id IN (252,139,189,214,250,281,283,414,415,433)
  AND (e.sku LIKE 'C%' OR e.sku LIKE 'TGS-%')
  AND w.sku IS NULL;

DELETE idx FROM catalog_category_product_index idx
JOIN catalog_product_entity e ON e.entity_id = idx.product_id
LEFT JOIN tmp_ai_want w ON w.sku = e.sku AND w.category_id = idx.category_id
WHERE idx.category_id IN (252,139,189,214,250,281,283,414,415,433)
  AND (e.sku LIKE 'C%' OR e.sku LIKE 'TGS-%')
  AND w.sku IS NULL;

-- 2) ADD every desired assignment that is missing (includes the 252 umbrella,
--    so no AI course can end up in a series without the parent).
INSERT IGNORE INTO catalog_category_product (category_id, product_id, position)
SELECT w.category_id, e.entity_id, 0
FROM tmp_ai_want w
JOIN catalog_product_entity e ON e.sku = w.sku;

-- 3) Mirror into the storefront index for every store on this instance.
INSERT IGNORE INTO catalog_category_product_index
  (category_id, product_id, position, is_parent, store_id, visibility)
SELECT cp.category_id, cp.product_id, cp.position, 1, s.store_id, vis.value
FROM catalog_category_product cp
JOIN catalog_product_entity e ON e.entity_id = cp.product_id
JOIN core_store s ON s.store_id > 0
JOIN catalog_product_entity_int vis
  ON vis.entity_id = cp.product_id AND vis.store_id = 0
 AND vis.attribute_id = (SELECT attribute_id FROM eav_attribute
                         WHERE entity_type_id = 4 AND attribute_code = 'visibility')
JOIN catalog_product_entity_int st
  ON st.entity_id = cp.product_id AND st.store_id = 0
 AND st.attribute_id = (SELECT attribute_id FROM eav_attribute
                        WHERE entity_type_id = 4 AND attribute_code = 'status')
WHERE cp.category_id IN (252,139,189,214,250,281,283,414,415,433)
  AND st.value = 1;

DROP TEMPORARY TABLE IF EXISTS tmp_ai_want;
