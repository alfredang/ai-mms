-- 1250: Fix and re-apply 1249 — the AI Courses landing page order.
--
-- 1249 resolved the category by url_key 'ai-courses', but category 252's
-- url_key is 'artificial-intelligence-courses' (the page is served at
-- /artificial-intelligence-courses.html; only its NAME is "AI Courses").
-- @ai therefore resolved to NULL, every UPDATE matched zero rows, and the
-- migration was a silent no-op — the page kept the sweep's own ordering.
--
-- Lesson: resolve categories by the url_key in the PAGE URL, and verify the
-- lookup returns a non-NULL id before trusting a position migration that
-- reports success. A CASE-based UPDATE against a NULL category is valid SQL
-- that changes nothing.
--
-- This file is 1249 with the correct url_key, including the
-- curated_url_keys entry (1249 added the wrong key 'ai-courses', which is
-- removed below since no such category exists).
--

-- Remove the bogus key 1249 appended.
UPDATE core_config_data
SET value = REPLACE(REPLACE(value, ',ai-courses,', ','), ',ai-courses', '')
WHERE path = 'mmd/category_ordering/curated_url_keys'
  AND scope = 'default' AND scope_id = 0;

SET @a_curlkey := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id = 3 AND attribute_code = 'url_key');

SET @ai := (
  SELECT v.entity_id FROM catalog_category_entity_varchar v
  WHERE v.attribute_id = @a_curlkey AND v.store_id = 0
    AND v.value = 'artificial-intelligence-courses' LIMIT 1
);

UPDATE core_config_data
SET value = CONCAT(value, ',artificial-intelligence-courses')
WHERE path = 'mmd/category_ordering/curated_url_keys'
  AND scope = 'default' AND scope_id = 0
  AND value NOT LIKE '%artificial-intelligence-courses%';

