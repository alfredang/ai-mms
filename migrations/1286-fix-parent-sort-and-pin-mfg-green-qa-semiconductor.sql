-- 1286: Make the WSQ parent listings actually honour their pinned order, and
-- pin three more categories.
--
-- ROOT CAUSE fixed here: six WSQ parent categories carry
-- default_sort_by = 'sku' at store 0, so the storefront sorts them BY SKU and
-- IGNORES catalog_category_product_index.position entirely. That is why the
-- sub-category grouping shipped in 1285 had no visible effect on WSQ IT &
-- Security (301), Finance & Accounting (334), Media & Marketing (72) and Soft
-- Skill & Business (160) even though the DB positions were correct — while
-- Sustainability & ESG (412), which has no override, worked immediately.
-- Also affects WSQ Funded Courses (292) and WSQ Mfg & Green (293).
-- Setting these to 'position' is what makes every pin in 1264-1285 visible.
-- (catalog/frontend/default_sort_by is already 'position' globally.)
--
-- Then:
--   * WSQ Mfg & Green (293) — group by sub-category in the order shown on the
--     page (Robotics & IoT, Sustainability & ESG, Quality Assurance,
--     Agriculture, Semiconductor), each child keeping its own curated order,
--     TGS- courses first and the single non-WSQ course (C711) last.
--   * WSQ Quality Assurance (288) — requested 17-course order. All 17 are
--     already in the category, including CLSSGB which the request flagged to
--     add, so no assignment is needed.
--   * WSQ Semiconductor (145) — requested 3-course order.
--
-- Positions are negative and dense so each block sits ahead of anything
-- unpinned. Business-key lookups only. Idempotent.

SET @a_dsb := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id = 3 AND attribute_code = 'default_sort_by');

UPDATE catalog_category_entity_varchar v
SET v.value = 'position'
WHERE v.attribute_id = @a_dsb
  AND v.value = 'sku'
  AND v.entity_id IN (
    SELECT entity_id FROM (
      SELECT uk.entity_id FROM catalog_category_entity_varchar uk
      JOIN eav_attribute a ON a.attribute_id = uk.attribute_id
       AND a.entity_type_id = 3 AND a.attribute_code = 'url_key'
      WHERE uk.store_id = 0 AND uk.value IN (
        'wsq-it-security-courses','wsq-finance-accounting-courses',
        'wsq-media-marketing-courses',
        'wsq-soft-skill-and-critical-core-skill-project-management-courses',
        'wsq-ibf-skillsfuture-utap-funded-courses','wsq-finance-mfg-green-courses')
    ) pick
  );

