-- The single non-WSQ course on 293 (C711) must sit BELOW every TGS- course,
-- including any that this migration did not pin (e.g. SKUs renamed on one
-- instance but not another). Pinning it at a fixed -1 would place it above such
-- rows, so give it a position strictly greater than every other row in the
-- category instead.
-- Compute the floor per store first: a correlated subquery cannot reference the
-- outer alias through a derived table (MySQL 1054), so materialise it.
DROP TEMPORARY TABLE IF EXISTS tmp_293_floor;
CREATE TEMPORARY TABLE tmp_293_floor (store_id SMALLINT PRIMARY KEY, pos INT);
INSERT INTO tmp_293_floor (store_id, pos)
SELECT i2.store_id, MAX(i2.position) + 1
FROM catalog_category_product_index i2
JOIN catalog_product_entity e2 ON e2.entity_id = i2.product_id
WHERE i2.category_id = @p_293 AND e2.sku LIKE 'TGS-%'
GROUP BY i2.store_id;

UPDATE catalog_category_product_index i
JOIN catalog_product_entity p ON p.entity_id = i.product_id
JOIN tmp_293_floor f ON f.store_id = i.store_id
SET i.position = f.pos
WHERE i.category_id = @p_293 AND @p_293 IS NOT NULL AND p.sku = 'C711';

DROP TEMPORARY TABLE IF EXISTS tmp_293_floor;

DROP TEMPORARY TABLE IF EXISTS tmp_293_bfloor;
CREATE TEMPORARY TABLE tmp_293_bfloor (pos INT);
INSERT INTO tmp_293_bfloor (pos)
SELECT COALESCE(MAX(c2.position),0) + 1
FROM catalog_category_product c2
JOIN catalog_product_entity e2 ON e2.entity_id = c2.product_id
WHERE c2.category_id = @p_293 AND e2.sku LIKE 'TGS-%';

UPDATE catalog_category_product cp
JOIN catalog_product_entity p ON p.entity_id = cp.product_id
JOIN tmp_293_bfloor f
SET cp.position = f.pos
WHERE cp.category_id = @p_293 AND @p_293 IS NOT NULL AND p.sku = 'C711';

DROP TEMPORARY TABLE IF EXISTS tmp_293_bfloor;

