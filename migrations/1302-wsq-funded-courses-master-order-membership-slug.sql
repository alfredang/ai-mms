WHERE id_path = CONCAT('category/', @cat) AND @cat IS NOT NULL
  AND request_path = 'wsq-ibf-skillsfuture-utap-funded-courses.html';

-- Permanent 301 old -> new, stores 0 and 1.
INSERT INTO core_url_rewrite
  (store_id, id_path, request_path, target_path, is_system, options, description)
SELECT s.store_id,
       CONCAT('category/', @cat, '-301'),
       'wsq-ibf-skillsfuture-utap-funded-courses.html',
       'wsq-funded-courses.html',
       0, 'RP', 'WSQ IBF SkillsFuture UTAP Funded Courses -> WSQ Funded Courses'
FROM (SELECT 0 AS store_id UNION ALL SELECT 1) s
WHERE @cat IS NOT NULL
ON DUPLICATE KEY UPDATE target_path = VALUES(target_path),
                        options     = VALUES(options),
                        is_system   = VALUES(is_system);

-- Re-point any existing RP row that targeted the old slug (no 301 chains).
UPDATE core_url_rewrite
SET target_path = 'wsq-funded-courses.html'
WHERE options = 'RP' AND target_path = 'wsq-ibf-skillsfuture-utap-funded-courses.html'
  AND @cat IS NOT NULL;

-- Fresh system rewrite so the new slug resolves before the next reindex.
INSERT INTO core_url_rewrite
  (store_id, id_path, request_path, target_path, is_system, options)
SELECT 1, CONCAT('category/', @cat), 'wsq-funded-courses.html',
       CONCAT('catalog/category/view/id/', @cat), 1, ''
FROM (SELECT 1) x
WHERE @cat IS NOT NULL
ON DUPLICATE KEY UPDATE target_path = VALUES(target_path);

-- EAV: drop store-scope overrides, write store 0.
DELETE v FROM catalog_category_entity_varchar v
JOIN eav_attribute a ON a.attribute_id = v.attribute_id AND a.entity_type_id = 3
WHERE v.entity_id = @cat AND @cat IS NOT NULL AND v.store_id <> 0
  AND a.attribute_code IN ('url_key','url_path','meta_title');

INSERT INTO catalog_category_entity_varchar (entity_type_id, attribute_id, store_id, entity_id, value)
SELECT 3, a.attribute_id, 0, @cat, t.val FROM (
  SELECT 'url_key'    AS code, 'wsq-funded-courses'        AS val UNION ALL
  SELECT 'url_path',  'wsq-funded-courses.html'                   UNION ALL
  SELECT 'meta_title','WSQ Funded Courses in Singapore'
) t JOIN eav_attribute a ON a.entity_type_id = 3 AND a.attribute_code = t.code
WHERE @cat IS NOT NULL
ON DUPLICATE KEY UPDATE value = VALUES(value);

