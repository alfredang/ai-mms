-- Media-gallery per-image label (rendered as the zoom img title/alt).
UPDATE catalog_product_entity_media_gallery_value gv
JOIN catalog_product_entity_media_gallery g ON g.value_id = gv.value_id
SET gv.label = 'Generative AI for Curriculum Development'
WHERE g.entity_id = @e505 AND @e505 IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Clear per-store overrides so partner store scopes can't shadow store 0.
-- ---------------------------------------------------------------------------

DELETE v FROM catalog_product_entity_varchar v
WHERE v.entity_id = @e505 AND v.store_id <> 0 AND @e505 IS NOT NULL
  AND v.attribute_id IN (@a_name, @a_uk, @a_mt, @a_il, @a_sil, @a_til);

DELETE v FROM catalog_product_entity_text v
WHERE v.entity_id = @e505 AND v.store_id <> 0 AND @e505 IS NOT NULL
  AND v.attribute_id IN (@a_short, @a_md, @a_mk);

-- Drop stale url_path rows at EVERY scope so the catalog_url reindex rebuilds
-- them from the new url_key rather than reusing the old slug. C505 has a live
-- store-1 row holding 'elearning-instructional-design.html'.
DELETE v FROM catalog_product_entity_varchar v
JOIN eav_attribute a ON a.attribute_id = v.attribute_id AND a.entity_type_id = 4 AND a.attribute_code = 'url_path'
WHERE v.entity_id = @e505 AND @e505 IS NOT NULL;
