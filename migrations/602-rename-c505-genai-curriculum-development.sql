-- Repurpose C505 "eLearning Instructional Design" -> "Generative AI for
-- Curriculum Development".
--
--   url_key: elearning-instructional-design -> generative-ai-for-curriculum-development
--
-- Rebrand + overview rewrite: name, url_key, short_description, meta_*, image
-- labels, and the media-gallery per-image label. The curriculum
-- (description), price and duration are intentionally KEPT — rewriting the
-- syllabus is a separate content task.
--
-- Categories are NOT changed. C505 sits in Instructional Design (13),
-- eLearning (299), eLearning Content Creation (377), Media & Design (69) and
-- Adult Courses (3). Curriculum development remains a legitimate fit for all
-- of them under the new title, and the user did not request a move.
--
-- The 301 from the old slug is NOT written here — core_url_rewrite must be
-- regenerated by the catalog_url reindex FIRST, otherwise the reindex
-- clobbers/re-points the row. See migration 603.
-- (memory: catalog_url reindex regenerates disabled-category 301 -> 404)
--
-- Includes the media-gallery label UPDATE that the 595 template omits — the
-- product-page zoom gallery renders that label as the img title/alt, so the
-- old course name leaks there otherwise.
-- (memory: feedback_course_repurpose_cross_site_rollout addendum 5, C597 run)
--
-- Clears per-store overrides of the rewritten attributes so partner store
-- scopes can't shadow store 0, and drops url_path at every scope (C505 has a
-- live store-1 url_path row holding the OLD slug — it would shadow the new
-- URL). Guarded with @e505 IS NOT NULL so it is a no-op on sites without this
-- SKU. Store scope 0. Idempotent. No content line ends in a semicolon.

SET @e505 := (SELECT entity_id FROM catalog_product_entity WHERE sku='C505');

SET @a_name  := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id=4 AND attribute_code='name');
SET @a_uk    := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id=4 AND attribute_code='url_key');
SET @a_short := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id=4 AND attribute_code='short_description');
SET @a_mt    := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id=4 AND attribute_code='meta_title');
SET @a_md    := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id=4 AND attribute_code='meta_description');
SET @a_mk    := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id=4 AND attribute_code='meta_keyword');
SET @a_il    := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id=4 AND attribute_code='image_label');
SET @a_sil   := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id=4 AND attribute_code='small_image_label');
SET @a_til   := (SELECT attribute_id FROM eav_attribute WHERE entity_type_id=4 AND attribute_code='thumbnail_label');

-- ---------------------------------------------------------------------------
-- C505 -> Generative AI for Curriculum Development
-- ---------------------------------------------------------------------------

